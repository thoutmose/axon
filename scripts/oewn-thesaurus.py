#!/usr/bin/env python3
# Usage: curl -LO https://github.com/globalwordnet/english-wordnet/releases/download/2024-edition/english-wordnet-2024.xml.gz
#        python3 -I scripts/oewn-thesaurus.py english-wordnet-2024.xml.gz api/internal/knowledge/thesaurus-en.txt
# Builds Axon's English thesaurus from Open English WordNet (CC BY 4.0):
# one line per synset, from each word's most common sense only, so rare
# senses do not link unrelated notes.
import gzip, re, sys, xml.etree.ElementTree as ET
src, dst = sys.argv[1], sys.argv[2]
word = re.compile(r"^[a-z]{3,20}$")
members = {}
for _, el in ET.iterparse(gzip.open(src), events=("end",)):
    if el.tag != "LexicalEntry":
        continue
    lemma = el.find("Lemma")
    senses = el.findall("Sense")
    if lemma is not None and senses and lemma.get("partOfSpeech") in ("n", "v", "a", "s"):
        w = lemma.get("writtenForm")
        if word.match(w):
            members.setdefault(senses[0].get("synset"), []).append(w)
    el.clear()
lines = sorted({", ".join(sorted(set(ws))) for ws in members.values() if 2 <= len(set(ws)) <= 8})
with open(dst, "w") as out:
    out.write("# Synonyms from Open English WordNet 2024 (https://github.com/globalwordnet/english-wordnet),\n")
    out.write("# licensed CC BY 4.0. Each word's most common sense only. Generated by scripts/oewn-thesaurus.py.\n")
    out.write("\n".join(lines) + "\n")
print(len(lines))
